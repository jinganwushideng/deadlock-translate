"""Deterministic source identity shared by the backend, VPK and installer.
Stamp before a development compile or full build; --check never modifies files.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from export_source import ROOT, public_files

GENERATED = {'build-info.json', 'src/Bridge/BuildInfo.Generated.cs'}

def identity(root=ROOT):
    digest = hashlib.sha256()
    for path in public_files(root):
        relative = path.relative_to(root).as_posix()
        if relative in GENERATED or relative.startswith(('tests/', 'docs/', 'LICENSES/')) or path.suffix in ('.md', '.png'):
            continue
        data = path.read_bytes()
        if path.suffix in ('.js', '.cs', '.json', '.html', '.css', '.ts', '.ps1', '.py', '.csproj', '.xml', '.manifest', '.cmd', '.tsv', '.yml', '.yaml', '.txt'):
            text = data.decode('utf-8-sig').replace('\r\n', '\n')
            if relative == 'mod/panorama/scripts/dlt_chat.js':
                text = re.sub(r"var BUILD_ID = '[^']*';", "var BUILD_ID = '__BUILD_ID__';", text)
            data = text.encode('utf-8')
        digest.update(relative.encode() + b'\0' + data + b'\0')
    version = json.loads((root/'version.json').read_text(encoding='utf-8-sig'))['version']
    return {'version': version, 'buildId': version+'-'+digest.hexdigest()[:12], 'sourceSha256': digest.hexdigest()}

def stamp(check=False):
    info = identity()
    source = '// Generated by scripts/build_identity.py; contains no machine or user data.\nnamespace DeadlockTranslate;\npublic static class BuildInfo { public const string Version = "'+info['version']+'"; public const string Id = "'+info['buildId']+'"; }\n'
    chat = ROOT/'mod/panorama/scripts/dlt_chat.js'
    text = chat.read_text(encoding='utf-8-sig')
    updated, count = re.subn(r"var BUILD_ID = '[^']*';", "var BUILD_ID = '"+info['buildId']+"';", text)
    if count != 1: raise ValueError('Exactly one chat build marker is required')
    outputs = {ROOT/'build-info.json': json.dumps(info, indent=2)+'\n', ROOT/'src/Bridge/BuildInfo.Generated.cs': source, chat: updated}
    for path, value in outputs.items():
        if check:
            if not path.is_file() or path.read_text(encoding='utf-8-sig') != value: raise ValueError('Build identity is stale: '+str(path.relative_to(ROOT)))
        else: path.write_text(value, encoding='utf-8')
    return info

if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true')
    print(json.dumps(stamp(parser.parse_args().check)))
